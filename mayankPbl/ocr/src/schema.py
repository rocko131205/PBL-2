"""FinVeritas V2 — Core Data Schemas

Defines the internal data models used throughout the system:
- NormalizedCompanyRecord: Source-agnostic company representation
- ProvenancedValue: Financial values with source tracking
- FactLedgerEntry / FinancialFactLedger: Deterministic computation results
- DSCRInputs / DSCRMethodology: DSCR calculation inputs and methodology documentation
- CreditAssessmentReport: Final lender-facing output
- PeerCompany / PeerComparison: Peer benchmarking data

Design principle: All financial math is done in Python. The LLM never touches
raw numbers — it only receives pre-computed fact ledger entries.
"""
from __future__ import annotations

from enum import Enum
from typing import Any, ClassVar, Dict, List, Optional, Union
from pydantic import BaseModel, Field


# -------------------------------------------------------------------------
# Enums
# -------------------------------------------------------------------------

class RiskLevel(str, Enum):
    LOW = "LOW"
    MODERATE = "MODERATE"
    HIGH = "HIGH"
    CRITICAL = "CRITICAL"
    INSUFFICIENT_DATA = "INSUFFICIENT_DATA"


class FactStatus(str, Enum):
    VALID = "VALID"
    ESTIMATED = "ESTIMATED"
    INSUFFICIENT_DATA = "INSUFFICIENT_DATA"
    NOT_APPLICABLE = "NOT_APPLICABLE"


class CheckStatus(str, Enum):
    PASS = "PASS"
    WARN = "WARN"
    FAIL = "FAIL"
    SKIP = "SKIP"


# -------------------------------------------------------------------------
# Core Financial Schemas
# -------------------------------------------------------------------------

class FinancialPeriod(BaseModel):
    """A single numeric observation tied to a reporting period."""
    period: str = Field(..., description="e.g. 2023-FY, 2024-Q1")
    value: float = Field(..., description="The financial value for this period")


class ProvenancedValue(BaseModel):
    """A financial value with full source provenance.

    Used for important extracted/computed values where traceability matters
    for explainability and credibility.
    """
    value: float
    unit: str = Field("absolute", description="e.g. absolute, %, ratio, days")
    currency: Optional[str] = Field(None, description="Currency code if monetary value")
    period: Optional[str] = Field(None, description="Reporting period e.g. 2023-FY")
    source: str = Field("unknown", description="Where this value came from: yfinance, fmp, pdf_ocr, user_input, computed")
    extraction_location: Optional[str] = Field(None, description="E.g. 'Income Statement > Operating Income', 'user form'")
    confidence: float = Field(1.0, ge=0.0, le=1.0, description="Confidence score 0-1")
    validation_status: FactStatus = Field(FactStatus.VALID)
    notes: Optional[str] = None


# -------------------------------------------------------------------------
# Fact Ledger — Contract Between Python and Agents
# -------------------------------------------------------------------------

class FactLedgerEntry(BaseModel):
    """A single computed metric in the fact ledger.

    Once generated by the Deterministic Metrics Engine, these values become
    the authoritative financial facts. Agents consume but never modify them.
    """
    metric: str = Field(..., description="Metric identifier e.g. 'revenue_growth_yoy'")
    display_name: str = Field(..., description="Human-readable name e.g. 'YoY Revenue Growth'")
    category: str = Field(..., description="E.g. 'revenue', 'profitability', 'liquidity', 'solvency', 'saas', 'dscr'")
    value: Optional[float] = Field(None, description="Computed value (None if insufficient data)")
    unit: str = Field("absolute", description="E.g. %, ratio, days, absolute")
    period: Optional[str] = Field(None, description="Reporting period")
    formula: Optional[str] = Field(None, description="Formula used: e.g. '(Revenue_T - Revenue_T-1) / Revenue_T-1 * 100'")
    inputs_used: List[str] = Field(default_factory=list, description="Source fields used in calculation")
    status: FactStatus = Field(FactStatus.VALID)
    risk_signal: Optional[CheckStatus] = Field(None, description="PASS/WARN/FAIL if this metric has a threshold")
    risk_detail: Optional[str] = Field(None, description="Why this risk signal was assigned")
    notes: Optional[str] = None


class FinancialFactLedger(BaseModel):
    """Complete set of computed metrics for a company analysis.

    This is the central contract between the deterministic computation layer
    and the agentic reasoning layer. Once computed, these facts are immutable.
    """
    entity_id: str
    analysis_timestamp: str
    currency: Optional[str] = None
    entries: List[FactLedgerEntry] = Field(default_factory=list)

    def get(self, metric: str) -> Optional[FactLedgerEntry]:
        """Retrieve a specific metric entry by name."""
        for e in self.entries:
            if e.metric == metric:
                return e
        return None

    def get_value(self, metric: str) -> Optional[float]:
        """Retrieve just the value for a metric."""
        entry = self.get(metric)
        return entry.value if entry else None

    def by_category(self, category: str) -> List[FactLedgerEntry]:
        """Retrieve all entries for a category."""
        return [e for e in self.entries if e.category == category]

    def risk_signals(self) -> List[FactLedgerEntry]:
        """Return all entries that have a risk signal set."""
        return [e for e in self.entries if e.risk_signal is not None]



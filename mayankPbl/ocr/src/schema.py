class CreditAssessmentReport(BaseModel):
    """The primary output of FinVeritas V2: an explainable credit-risk assessment.

    This is NOT a loan approval/rejection. It is a decision-support document
    for a lending institution or financial analyst.
    """
    entity_id: str
    analysis_date: str
    currency: Optional[str] = None

    # DSCR
    dscr_result: Optional[DSCRResult] = None

    # Financial profile summary
    financial_summary: Dict[str, Any] = Field(default_factory=dict)

    # SaaS analysis
    saas_classification: Optional[str] = None
    saas_metrics: Dict[str, Any] = Field(default_factory=dict)

    # Peer comparison
    peer_comparison: Optional[PeerComparison] = None

    # Risk assessment
    risk_dashboard: Optional[RiskDashboard] = None

    # Qualitative findings
    qualitative_findings: List[str] = Field(default_factory=list)

    # Synthesized assessment
    major_strengths: List[str] = Field(default_factory=list)
    major_risks: List[str] = Field(default_factory=list)
    data_quality_notes: List[str] = Field(default_factory=list)
    missing_information: List[str] = Field(default_factory=list)
    assumptions: List[str] = Field(default_factory=list)

    # Final assessment
    risk_classification: RiskLevel = Field(RiskLevel.MODERATE)
    recommendation_narrative: str = Field("", description="Explainable recommendation for the analyst")

    # Metadata
    methodology_notes: List[str] = Field(default_factory=list)
    disclaimer: str = Field(
        "This assessment is a decision-support tool for qualified analysts. "
        "It does not constitute a loan approval, rejection, or binding credit decision. "
        "The lending institution remains responsible for the final lending decision."
    )

class RiskIndicator(BaseModel):
    """A single deterministic risk signal."""
    name: str
    category: str = Field(..., description="profitability, liquidity, solvency, growth, saas, debt_service")
    status: CheckStatus
    value: Optional[float] = None
    threshold: Optional[str] = None
    detail: str = Field("", description="Human-readable explanation")
    severity_weight: float = Field(1.0, description="Relative importance 0-3")


class RiskDashboard(BaseModel):
    """Consolidated risk indicators from all calculators."""
    entity_id: str
    indicators: List[RiskIndicator] = Field(default_factory=list)
    overall_risk: RiskLevel = RiskLevel.MODERATE

    @property
    def fail_count(self) -> int:
        return sum(1 for i in self.indicators if i.status == CheckStatus.FAIL)

    @property
    def warn_count(self) -> int:
        return sum(1 for i in self.indicators if i.status == CheckStatus.WARN)



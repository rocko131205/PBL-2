class DSCRInputs(BaseModel):
    """Inputs required for calculating Debt Service Coverage Ratio.

    V2: Extended with loan terms and repayment structure.
    """
    # Existing debt obligations
    existing_loan_principal_repayment: float = Field(0.0, description="Annual principal repayment on existing debt")
    existing_loan_interest: float = Field(0.0, description="Annual interest on existing debt")

    # Proposed new debt
    proposed_loan_principal_repayment: float = Field(0.0, description="Proposed new annual principal repayment")
    proposed_loan_interest: float = Field(0.0, description="Proposed new annual interest")

    # V2: Loan structure details
    proposed_loan_amount: Optional[float] = Field(None, description="Total proposed loan amount")
    proposed_tenure_years: Optional[float] = Field(None, description="Loan tenure in years")
    proposed_interest_rate: Optional[float] = Field(None, description="Annual interest rate as percentage")
    repayment_structure: Optional[str] = Field(None, description="E.g. 'equal_installment', 'bullet', 'balloon'")

    @property
    def total_existing_debt_service(self) -> float:
        return self.existing_loan_principal_repayment + self.existing_loan_interest

    @property
    def total_proposed_debt_service(self) -> float:
        return self.proposed_loan_principal_repayment + self.proposed_loan_interest

    @property
    def total_annual_debt_service(self) -> float:
        return (self.existing_loan_principal_repayment + self.existing_loan_interest +
                self.proposed_loan_principal_repayment + self.proposed_loan_interest)


class DSCRMethodology(BaseModel):
    """Documents the DSCR calculation methodology used.

    Required for explainability — the analyst needs to know exactly how
    DSCR was computed and what assumptions were made.
    """
    numerator_name: str = Field(..., description="E.g. 'EBITDA', 'Operating Income', 'Net Operating Income'")
    numerator_formula: str = Field(..., description="How the numerator was derived")
    numerator_source: str = Field(..., description="Where the numerator data came from")
    denominator_components: List[str] = Field(default_factory=list, description="What's included in debt service")
    time_period: str = Field(..., description="E.g. 'Most recent FY', 'Average of last 3 FY'")
    assumptions: List[str] = Field(default_factory=list, description="Key assumptions made")
    limitations: List[str] = Field(default_factory=list, description="Known limitations of this calculation")
    data_quality_notes: Optional[str] = None


class DSCRResult(BaseModel):
    """Complete DSCR calculation result with methodology."""
    numerator_value: float = Field(..., description="Net operating income / EBITDA used")
    denominator_value: float = Field(..., description="Total annual debt service")
    dscr_ratio: Optional[float] = Field(None, description="DSCR = numerator / denominator")
    risk_level: RiskLevel = Field(RiskLevel.INSUFFICIENT_DATA)
    methodology: DSCRMethodology
    interpretation: Optional[str] = Field(None, description="Context-aware interpretation")



class NormalizedCompanyRecord(BaseModel):
    """Standardized internal representation of a company, regardless of source
    (Bloomberg PDF, Ticker, or CSV).

    V2 additions: country, jurisdiction, SaaS classification, company
    description, and provenance tracking.
    """
    entity_id: str = Field(..., description="Company name or ticker symbol")
    source: str = Field(..., description="E.g., bloomberg_pdf, ticker, csv, user_input")
    currency: Optional[str] = Field(None, description="Currency code, e.g., USD, INR")

    # V2: Company identity & classification
    country: Optional[str] = Field(None, description="Country of domicile e.g. 'US', 'IN', 'DE'")
    jurisdiction: Optional[str] = Field(None, description="Primary regulatory jurisdiction")
    industry: Optional[str] = Field(None, description="Industry classification")
    saas_subtype: Optional[str] = Field(None, description="SaaS subcategory e.g. 'CRM', 'HCM', 'Security', 'Infrastructure'")
    company_description: Optional[str] = Field(None, description="Brief description of what the company does")
    is_public: Optional[bool] = Field(None, description="Whether the company is publicly traded")
    ticker_symbol: Optional[str] = Field(None, description="Stock ticker if public")

    # Standard Financials (time series)
    revenue: List[FinancialPeriod] = Field(default_factory=list)
    cost_of_revenue: List[FinancialPeriod] = Field(default_factory=list)
    gross_profit: List[FinancialPeriod] = Field(default_factory=list)
    operating_income: List[FinancialPeriod] = Field(default_factory=list)
    net_operating_income: List[FinancialPeriod] = Field(default_factory=list)
    ebitda: List[FinancialPeriod] = Field(default_factory=list)
    net_income: List[FinancialPeriod] = Field(default_factory=list)
    interest_expense: List[FinancialPeriod] = Field(default_factory=list)
    depreciation: List[FinancialPeriod] = Field(default_factory=list)
    pretax_income: List[FinancialPeriod] = Field(default_factory=list)
    income_tax: List[FinancialPeriod] = Field(default_factory=list)

    # Balance sheet
    total_assets: List[FinancialPeriod] = Field(default_factory=list)
    total_liabilities: List[FinancialPeriod] = Field(default_factory=list)
    current_assets: List[FinancialPeriod] = Field(default_factory=list)
    current_liabilities: List[FinancialPeriod] = Field(default_factory=list)
    equity: List[FinancialPeriod] = Field(default_factory=list)
    total_debt: List[FinancialPeriod] = Field(default_factory=list)
    long_term_debt: List[FinancialPeriod] = Field(default_factory=list)
    short_term_debt: List[FinancialPeriod] = Field(default_factory=list)
    cash_and_equivalents: List[FinancialPeriod] = Field(default_factory=list)
    non_current_assets: List[FinancialPeriod] = Field(default_factory=list)
    non_current_liabilities: List[FinancialPeriod] = Field(default_factory=list)
    retained_earnings: List[FinancialPeriod] = Field(default_factory=list)
    accounts_receivable: List[FinancialPeriod] = Field(default_factory=list)
    inventory: List[FinancialPeriod] = Field(default_factory=list)
    accounts_payable: List[FinancialPeriod] = Field(default_factory=list)

    # Cash flow statement (V3: critical for real debt-service analysis)
    operating_cash_flow: List[FinancialPeriod] = Field(default_factory=list)
    capital_expenditure: List[FinancialPeriod] = Field(default_factory=list)
    free_cash_flow: List[FinancialPeriod] = Field(default_factory=list)

    # Per-share
    basic_eps: List[FinancialPeriod] = Field(default_factory=list)
    diluted_eps: List[FinancialPeriod] = Field(default_factory=list)

    # SaaS-specific or Derived Info
    saas_metrics: Dict[str, Any] = Field(default_factory=dict, description="e.g. ARR, CAC, NRR if available")
    qualitative_context: Optional[str] = Field(None, description="Extracted management commentary or notes")

    # V2: Provenance
    source_provenance: Dict[str, str] = Field(
        default_factory=dict,
        description="Map of field_name → source (e.g. 'revenue': 'yfinance', 'total_assets': 'fmp')"
    )

    # V3: Currency normalization
    original_currency: Optional[str] = Field(None, description="Native currency before FX conversion, if converted")
    fx_rate_used: Optional[float] = Field(None, description="FX rate applied (1 original_currency = fx_rate base_currency)")
    is_currency_normalized: bool = Field(False, description="True once monetary values are converted to a base currency")

    def latest_value(self, field_name: str) -> Optional[float]:
        """Get the most recent value for a given financial field."""
        series: List[FinancialPeriod] = getattr(self, field_name, [])
        if not series:
            return None
        sorted_series = sorted(series, key=lambda x: x.period)
        return sorted_series[-1].value

    def has_field(self, field_name: str) -> bool:
        """Check if a financial field has any data."""
        series: List[FinancialPeriod] = getattr(self, field_name, [])
        return bool(series)

    # All time-series financial fields (single source of truth).
    FINANCIAL_FIELDS: ClassVar[List[str]] = [
        "revenue", "cost_of_revenue", "gross_profit", "operating_income",
        "net_operating_income", "ebitda", "net_income", "interest_expense",
        "depreciation", "pretax_income", "income_tax",
        "operating_cash_flow", "capital_expenditure", "free_cash_flow",
        "total_assets", "total_liabilities", "current_assets", "current_liabilities",
        "equity", "total_debt", "long_term_debt", "short_term_debt",
        "cash_and_equivalents", "non_current_assets", "non_current_liabilities",
        "retained_earnings", "accounts_receivable", "inventory", "accounts_payable",
        "basic_eps", "diluted_eps",
    ]

    # Fields expressed in currency (converted during FX normalization).
    # Per-share (EPS) values are NOT scaled — they are already per-share amounts,
    # but they ARE currency-denominated, so they are converted too.
    MONETARY_FIELDS: ClassVar[List[str]] = [
        "revenue", "cost_of_revenue", "gross_profit", "operating_income",
        "net_operating_income", "ebitda", "net_income", "interest_expense",
        "depreciation", "pretax_income", "income_tax",
        "operating_cash_flow", "capital_expenditure", "free_cash_flow",
        "total_assets", "total_liabilities", "current_assets", "current_liabilities",
        "equity", "total_debt", "long_term_debt", "short_term_debt",
        "cash_and_equivalents", "non_current_assets", "non_current_liabilities",
        "retained_earnings", "accounts_receivable", "inventory", "accounts_payable",
        "basic_eps", "diluted_eps",
    ]

    def available_fields(self) -> List[str]:
        """Return list of financial fields that have data."""
        return [f for f in self.FINANCIAL_FIELDS if self.has_field(f)]

    def completeness(self) -> Dict[str, Any]:
        """Report which financial fields are present vs missing.

        Returns a dict with present fields, missing fields, and a 0-100 score,
        so the UI can show the user exactly what data was captured before analysis.
        """
        present = self.available_fields()
        missing = [f for f in self.FINANCIAL_FIELDS if f not in present]
        total = len(self.FINANCIAL_FIELDS)
        return {
            "present": present,
            "missing": missing,
            "present_count": len(present),
            "total_count": total,
            "score": round(len(present) / total * 100, 1) if total else 0.0,
        }



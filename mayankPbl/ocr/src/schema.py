class PeerCompany(BaseModel):
    """A peer company with actual financial data (not LLM-estimated)."""
    entity_id: str
    ticker: Optional[str] = None
    country: Optional[str] = None
    saas_subtype: Optional[str] = None
    revenue_scale: Optional[str] = None
